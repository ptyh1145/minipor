"""omod2obj — convert the game's .omod skinned-mesh container into Wavefront OBJ/MTL.

Usage:
    python omod2obj.py <assets-dir> <out-dir> [--only subdir]

Container grammar (recovered by static analysis):
    magic 89 67 45 23 | u32 100 | u32 childCount
    node := u16 type, u8 nameLen, name[nameLen], payload
SubMeshData payload:
    u32 a | u32 b | u32 indexCount | u16 indices[indexCount]
    <20-byte vertex-stream header>
    vertices[N] of 40 bytes: pos(3f) normal(3f) uv(2f) unknown(2f)
"""
from __future__ import annotations

import argparse
import os
import re
import struct
import sys

MAGIC = b"\x89\x67\x45\x23"
VERTEX_STRIDE = 40
VERTEX_HEADER = 20
TEXTURE_RE = re.compile(rb"[ -~]{4,}\.(?:png|jpg|jpeg|tga|dds)", re.IGNORECASE)


# --------------------------------------------------------------------------- container
def scan_nodes(data: bytes):
    """Yield (offset, type, name, name_end) for every plausible node header."""
    i = 4
    n = len(data)
    while i < n - 4:
        typ = struct.unpack_from("<H", data, i)[0]
        ln = data[i + 2]
        if 0x60 <= typ <= 0x90 and 2 <= ln <= 48 and i + 3 + ln <= n:
            raw = data[i + 3:i + 3 + ln]
            if all(32 <= c < 127 for c in raw):
                yield i, typ, raw.decode("ascii"), i + 3 + ln
                i += 3 + ln
                continue
        i += 1


def parse_omod(path: str) -> dict:
    data = open(path, "rb").read()
    if data[:4] != MAGIC:
        raise ValueError("not an omod container")
    nodes = list(scan_nodes(data))

    submeshes = []
    materials = []
    for idx, (off, typ, name, name_end) in enumerate(nodes):
        end = nodes[idx + 1][0] if idx + 1 < len(nodes) else len(data)
        payload = data[name_end:end]
        if name == "SubMeshData":
            if len(payload) < 12 + VERTEX_HEADER + VERTEX_STRIDE:
                continue
            a, b, icount = struct.unpack_from("<3I", payload, 0)
            vbase = 12 + 2 * icount
            if vbase + VERTEX_HEADER > len(payload):
                continue
            start = vbase + VERTEX_HEADER
            body = len(payload) - start
            stride = 0
            for candidate in (VERTEX_STRIDE, 64, 32):
                if body % candidate == 0 and body // candidate > 0:
                    stride = candidate
                    break
            if not stride:
                continue
            vcount = body // stride
            if vcount <= 0:
                continue
            indices = struct.unpack_from(f"<{icount}H", payload, 12) if icount else ()
            verts = []
            for k in range(vcount):
                px, py, pz, nx, ny, nz, u, w = struct.unpack_from(
                    "<8f", payload, start + k * stride)
                verts.append(((px, py, pz), (nx, ny, nz), (u, w)))
            submeshes.append(dict(a=a, b=b, indices=indices, verts=verts, stride=stride))
        elif name == "Material":
            hit = TEXTURE_RE.search(payload)
            materials.append(hit.group().decode("latin-1") if hit else None)

    return dict(path=path, submeshes=submeshes, materials=materials)


# --------------------------------------------------------------------------- writers
def write_obj(model: dict, out_dir: str, stem: str) -> tuple[str, int, int]:
    os.makedirs(out_dir, exist_ok=True)
    obj_path = os.path.join(out_dir, stem + ".obj")
    mtl_path = os.path.join(out_dir, stem + ".mtl")
    base = 0
    tris = 0
    verts_total = 0

    mtl_lines = ["# generated by omod2obj"]
    used_textures = []
    for i, mat in enumerate(model["materials"]):
        name = f"mat_{i}"
        tex = mat or ""
        mtl_lines += [f"newmtl {name}", "Kd 1 1 1", "Ka 0.2 0.2 0.2"]
        if tex:
            mtl_lines.append(f"map_Kd {tex.replace(chr(92), '/')}")
            used_textures.append(tex)
        mtl_lines.append("")

    with open(obj_path, "w", encoding="utf-8") as fh:
        fh.write(f"# converted from {os.path.basename(model['path'])}\n")
        fh.write(f"mtllib {stem}.mtl\n")
        for si, sm in enumerate(model["submeshes"]):
            fh.write(f"\ng submesh_{si}_tris{len(sm['indices']) // 3}\n")
            if si < len(model["materials"]):
                fh.write(f"usemtl mat_{si}\n")
            for pos, nrm, uv in sm["verts"]:
                fh.write(f"v {pos[0]:.6f} {pos[1]:.6f} {pos[2]:.6f}\n")
            for _pos, nrm, _uv in sm["verts"]:
                fh.write(f"vn {nrm[0]:.6f} {nrm[1]:.6f} {nrm[2]:.6f}\n")
            for _pos, _nrm, uv in sm["verts"]:
                fh.write(f"vt {uv[0]:.6f} {uv[1]:.6f}\n")
            idx = sm["indices"]
            for t in range(0, len(idx) - 2, 3):
                a, b, c = idx[t], idx[t + 1], idx[t + 2]
                if max(a, b, c) >= len(sm["verts"]):
                    continue
                fa, fb, fc = (base + a + 1, base + b + 1, base + c + 1)
                fh.write(f"f {fa}/{fa}/{fa} {fb}/{fb}/{fb} {fc}/{fc}/{fc}\n")
                tris += 1
            base += len(sm["verts"])
            verts_total += len(sm["verts"])

    with open(mtl_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(mtl_lines))
    return obj_path, verts_total, tris


def convert_tree(src: str, dst: str, only: str | None = None) -> None:
    total_models = total_tris = total_verts = failed = 0
    for root, _dirs, files in os.walk(src):
        if only and only.lower() not in root.lower():
            continue
        for f in sorted(files):
            if not f.lower().endswith(".omod"):
                continue
            path = os.path.join(root, f)
            rel = os.path.relpath(path, src)
            stem = os.path.splitext(rel)[0].replace("\\", "_")
            try:
                model = parse_omod(path)
                if not model["submeshes"]:
                    continue
                obj, v, t = write_obj(model, dst, stem)
                total_models += 1
                total_verts += v
                total_tris += t
                print(f"  {rel:<34} -> {os.path.basename(obj):<40} v={v:<5} tris={t}")
            except Exception as exc:  # noqa: BLE001
                failed += 1
                print(f"  {rel}: FAILED {exc}")
    print(f"\nmodels={total_models} vertices={total_verts:,} triangles={total_tris:,} failed={failed}")


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description="convert .omod meshes to Wavefront OBJ")
    ap.add_argument("src", help="assets directory")
    ap.add_argument("dst", help="output directory")
    ap.add_argument("--only", default=None, help="only paths containing this substring")
    args = ap.parse_args(argv)
    convert_tree(args.src, args.dst, args.only)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
